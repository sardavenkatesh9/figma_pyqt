def _render_shadow(w: int, h: int, radius: int, blur: float, rgba: RGBA, margin: int) -> QPixmap:
    """A blurred rounded rectangle, rendered once through an off-screen scene."""
    size = QSize(w + 2 * margin, h + 2 * margin)
    shape = QImage(size, QImage.Format.Format_ARGB32_Premultiplied)
    shape.fill(Qt.GlobalColor.transparent)
    painter = QPainter(shape)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    painter.setPen(Qt.PenStyle.NoPen)
    painter.setBrush(QColor(*rgba))
    painter.drawRoundedRect(QRectF(margin, margin, w, h), radius, radius)
    painter.end()

    scene = QGraphicsScene(QRectF(0, 0, size.width(), size.height()))
    item = QGraphicsPixmapItem(QPixmap.fromImage(shape))
    effect = QGraphicsBlurEffect()
    effect.setBlurRadius(blur / 2)
    effect.setBlurHints(QGraphicsBlurEffect.BlurHint.QualityHint)
    item.setGraphicsEffect(effect)
    scene.addItem(item)
    result = QImage(size, QImage.Format.Format_ARGB32_Premultiplied)
    result.fill(Qt.GlobalColor.transparent)
    painter = QPainter(result)
    scene.render(painter)
    painter.end()
    return QPixmap.fromImage(result)


