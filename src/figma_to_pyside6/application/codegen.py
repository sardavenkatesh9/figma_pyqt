@dataclass(frozen=True, slots=True)
class PagePlan:
    """A frame together with the module and class names its page will use."""

    frame: FigmaFrame
    slug: str
    class_name: str

    @property
    def module_file(self) -> str:
        """File name of the page module."""
        return f"{self.slug}_page.py"


@dataclass(slots=True)
class RenderedPage:
    """Generated page source plus what had to be skipped to produce it."""

    source: str
    warnings: list[str] = field(default_factory=list)


class SlugAllocator:
    """Hands out unique, importable module slugs for frame names.

    Remembering the next numeric suffix per base slug makes n identical names cost O(n)
    overall, where re-probing ``_2``, ``_3``, ... from scratch each time costs O(n^2).
    """

    def __init__(self) -> None:
        """Start with no slugs taken."""
        self._taken: set[str] = set()
        self._next_suffix: dict[str, int] = {}

    def allocate(self, name: str) -> str:
        """Return a slug for ``name`` that has not been returned before."""
        slug = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower() or "screen"
        if slug[0].isdigit() or keyword.iskeyword(slug):
            slug = f"screen_{slug}"
        candidate = slug
        while candidate in self._taken:
            suffix = self._next_suffix.get(slug, 2)
            self._next_suffix[slug] = suffix + 1
            candidate = f"{slug}_{suffix}"
        self._taken.add(candidate)
        return candidate


def class_name_for(slug: str) -> str:
    """Return the PascalCase page class name for a slug."""
    return "".join(part.capitalize() for part in slug.split("_") if part) + "Page"


def plan_pages(frames: list[FigmaFrame]) -> list[PagePlan]:
    """Assign a unique module and class name to every frame."""
    allocator = SlugAllocator()
    plans = []
    for frame in frames:
        slug = allocator.allocate(frame.name)
        plans.append(PagePlan(frame, slug, class_name_for(slug)))
    return plans


def _label(node: FigmaNode) -> str:
    """A single-line, ASCII-safe node name for source comments."""
    return re.sub(r"[^\x20-\x7e]+", " ", node.name).strip()[:_NAME_LIMIT]


def _fill_layers(node: FigmaNode) -> list[Paint]:
    """Fills that a box can paint, bottom layer first (bitmap fills are exported instead)."""
    return [paint for paint in node.fills if paint.kind in _FILL_KINDS]


def _top_stroke(node: FigmaNode) -> Paint | None:
    return next((s for s in reversed(node.strokes) if s.kind in _FILL_KINDS), None)


def _opacity_arg(factor: float) -> str:
    return f", opacity={factor:.3f}" if factor < 0.999 else ""


def _apply_case(content: str, case: str) -> str:
    if case == "UPPER":
        return content.upper()
    if case == "LOWER":
        return content.lower()
    if case == "TITLE":
        return content.title()
    return content


def _text_color(node: FigmaNode, factor: float) -> str:
    paint = next((p for p in reversed(node.fills) if p.kind in _FILL_KINDS), None)
    if paint is None:
        return css_color(Color(0, 0, 0), factor)
    color = paint.color or (paint.stops[0].color if paint.stops else None)
    return css_color(color, paint.opacity * factor) if color else css_color(Color(0, 0, 0), factor)


class PageEmitter:
    """Walks a frame's node tree and emits one helper call per visible layer."""

    def __init__(self, plan: PagePlan, assets: Mapping[str, str]) -> None:
        """``assets`` maps a raster layer's node id to the PNG file that holds its export."""
        self.plan = plan
        self.frame = plan.frame
        self.assets = assets
        self.lines: list[str] = []
        self.skipped_rasters = 0
        self._counter = 0
        self._used: set[str] = {"decorate"}
        self._stack: list[tuple[FigmaNode, str]] = []  # ancestors of the node being emitted
        self._factors: list[float] = [plan.frame.opacity]  # opacity inherited down the tree

    def render(self) -> RenderedPage:
        """Emit the whole page module."""
        frame = self.frame
        self._emit_root_layers(frame)
        self._stack.append((frame, "canvas"))
        self._emit_children(frame, "canvas")
        warnings = []
        if self.skipped_rasters:
            warnings.append(
                f"{frame.name}: {self.skipped_rasters} vector/image layer(s) were left out "
                "because no exported image was available (connect to Figma to include them)"
            )
        return RenderedPage(self._source(), warnings)

    def _source(self) -> str:
        frame = self.frame
        helpers = ", ".join(sorted(self._used))
        header = [
            GENERATED_MARKER,
            "from __future__ import annotations",
            "",
            "from PySide6.QtWidgets import QWidget",
            "",
            "from src.ui.pages.base_page import BasePage",
            f"from src.ui.pages.widgets import {helpers}",
            "",
            "",
            f"class {self.plan.class_name}(BasePage):",
            f"    TITLE = {json.dumps(frame.name)}",
            f"    FRAME_SIZE = ({max(frame.width, 1)}, {max(frame.height, 1)})",
            "",
            "    def build_canvas(self, canvas: QWidget) -> None:",
            f"        {json.dumps(f'Widgets for Figma frame {frame.name} ({frame.node_id}).')}",
        ]
        return "\n".join([*header, *self.lines, ""])

    # ----------------------------------------------------------------- emission
    def _var(self) -> str:
        self._counter += 1
        return f"n{self._counter}"

    def _emit_root_layers(self, frame: FigmaFrame) -> None:
        layers = _fill_layers(frame)
        width, height = max(frame.width, 1), max(frame.height, 1)
        stroke = _top_stroke(frame)
        base = box_qss(
            layers[0] if layers else None,
            stroke if len(layers) <= 1 else None,
            frame.stroke_weight,
            frame.corner_radii,
            width,
            height,
            self._factors[-1],
        )
        self.lines.append(f"{_INDENT}decorate(canvas, {json.dumps(base)})")
        self._emit_overlays(
            frame, "canvas", layers[1:], stroke, frame.corner_radii, self._factors[-1]
        )

    def _emit_overlays(
        self,
        node: FigmaNode,
        parent_var: str,
        extra: list[Paint],
        stroke: Paint | None,
        radii: Radii | None,
        factor: float,
    ) -> None:
        """Extra fill layers become child boxes covering the node; the stroke goes on top."""
        width, height = max(node.width, 1), max(node.height, 1)
        for index, paint in enumerate(extra):
            last = index == len(extra) - 1
            qss = box_qss(
                paint, stroke if last else None, node.stroke_weight, radii, width, height, factor
            )
            self._used.add("box")
            self.lines.append(
                f"{_INDENT}box({parent_var}, 0, 0, {width}, {height}, {json.dumps(qss)})"
            )

    def _emit_children(self, parent: FigmaNode, parent_var: str) -> None:
        for child in renderable_children(parent):
            if needs_raster(child):
                self._emit_raster(child, parent, parent_var)
            elif child.type == "TEXT":
                self._emit_text(child, parent, parent_var)
            else:
                self._emit_box(child, parent, parent_var)

    def _emit_raster(self, node: FigmaNode, parent: FigmaNode, parent_var: str) -> None:
        name = self.assets.get(node.node_id)
        if too_large(node) or name is None:
            self.skipped_rasters += 1
            return
        x, y, w, h = raster_bounds(node)
        factor = self._factors[-1] * node.opacity
        self._used.add("image")
        self.lines.append(
            f"{_INDENT}image({parent_var}, {json.dumps(name)}, {x - parent.x}, {y - parent.y}, "
            f"{max(w, 1)}, {max(h, 1)}{_opacity_arg(factor)})  # {_label(node)}"
        )

    def _emit_text(self, node: FigmaNode, parent: FigmaNode, parent_var: str) -> None:
        raw_text = node.characters or node.name  # offline JSON may lack ``characters``
        if not raw_text:
            return
        style = node.text_style or TextStyle()
        x, y = node.x, node.y  # absolute for now; made relative to the host below
        width, height = max(node.width, 1), max(node.height, 1)
        line_height = style.line_height or style.font_size * 1.2
        wrap = height > 1.6 * line_height
        align_v = style.align_v
        if not wrap:
            # Fallback fonts are wider and taller than Figma's: widen the box and grow it
            # evenly above and below the line so glyphs (and descenders) are never clipped.
            needed = round(style.font_size * 1.5)
            if height < needed:
                y -= (needed - height) // 2
                height = needed
            align_v = "CENTER"
            pad = max(10, round(0.2 * width))
            if style.align_h == "RIGHT":
                x, width = x - pad, width + pad
            elif style.align_h == "CENTER":
                x, width = x - pad // 2, width + pad
            else:
                width += pad
        host, host_var = self._text_host(x, y, width, height)
        x, y = x - host.x, y - host.y
        extras = ""
        if style.align_h != "LEFT":
            extras += f", align_h={style.align_h!r}"
        if align_v != "TOP":
            extras += f", align_v={align_v!r}"
        if style.letter_spacing:
            extras += f", spacing={style.letter_spacing:.2f}"
        if style.italic:
            extras += ", italic=True"
        if style.underline:
            extras += ", underline=True"
        if wrap:
            extras += ", wrap=True"
        content = json.dumps(_apply_case(raw_text, style.text_case))
        self._used.add("text")
        self.lines.append(
            f"{_INDENT}text({host_var}, {content}, {x}, {y}, {width}, {height}, "
            f"{json.dumps(style.font_family)}, {style.font_size:g}, {style.font_weight}, "
            f"{json.dumps(_text_color(node, self._factors[-1] * node.opacity))}{extras})"
        )

    def _text_host(self, x: int, y: int, width: int, height: int) -> tuple[FigmaNode, str]:
        """The nearest ancestor that fully contains the (possibly enlarged) text box.

        Qt clips children to their parent, and a label grown to fit a fallback font can
        stick out of a tight text container, so such labels move up the tree. Opacity is
        baked into the colors, so moving a label up never changes how it looks.
        """
        for node, var in reversed(self._stack):
            if (
                x >= node.x
                and y >= node.y
                and x + width <= node.x + node.width
                and y + height <= node.y + node.height
            ):
                return node, var
        return self._stack[-1]

    def _emit_box(self, node: FigmaNode, parent: FigmaNode, parent_var: str) -> None:
        width, height = max(node.width, 1), max(node.height, 1)
        radii = node.corner_radii
        if node.type == "ELLIPSE":
            half = min(width, height) / 2
            radii = (half, half, half, half)
        layers = _fill_layers(node)
        stroke = _top_stroke(node)
        factor = self._factors[-1] * node.opacity
        qss = box_qss(
            layers[0] if layers else None,
            stroke if len(layers) <= 1 else None,
            node.stroke_weight,
            radii,
            width,
            height,
            factor,
        )
        x, y = node.x - parent.x, node.y - parent.y
        self._emit_shadow(node, parent_var, (x, y, width, height), radii, factor)
        var = self._var()
        self._used.add("box")
        self.lines.append(
            f"{_INDENT}{var} = box({parent_var}, {x}, {y}, {width}, {height}, "
            f"{json.dumps(qss)})  # {_label(node)}"
        )
        self._emit_overlays(node, var, layers[1:], stroke, radii, factor)
        self._stack.append((node, var))
        self._factors.append(factor)
        self._emit_children(node, var)
        self._factors.pop()
        self._stack.pop()

    def _emit_shadow(
        self,
        node: FigmaNode,
        parent_var: str,
        rect: tuple[int, int, int, int],
        radii: Radii | None,
        factor: float,
    ) -> None:
        """A drop shadow is a pre-blurred picture created just before (so behind) the box."""
        effect = next((e for e in node.effects if e.kind == "DROP_SHADOW"), None)
        if effect is None or effect.radius <= 0:
            return
        x, y, width, height = rect
        corner = round(min(radii[0] if radii else 0, width / 2, height / 2))
        c = effect.color
        rgba = (round(c.r * 255), round(c.g * 255), round(c.b * 255), round(c.a * factor * 255))
        self._used.add("shadow")
        self.lines.append(
            f"{_INDENT}shadow({parent_var}, {x}, {y}, {width}, {height}, {corner}, "
            f"{effect.radius:g}, {effect.offset_x:g}, {effect.offset_y:g}, {rgba})"
        )


def render_page(plan: PagePlan, assets: Mapping[str, str] | None = None) -> RenderedPage:
    """Render one page module.

    Args:
        plan: The frame and the class/module names chosen for it.
        assets: PNG file name per node id for the layers that were exported; layers
            without an entry are left out and reported.
    """
    return PageEmitter(plan, assets or {}).render()


def nav_titles(plans: list[PagePlan]) -> list[str]:
    """Sidebar titles in page order; repeated frame names get " (2)", " (3)", ... appended."""
    totals: dict[str, int] = {}
    for plan in plans:
        totals[plan.frame.name] = totals.get(plan.frame.name, 0) + 1
    seen: dict[str, int] = {}
    titles = []
    for plan in plans:
        name = plan.frame.name
        seen[name] = seen.get(name, 0) + 1
        titles.append(name if totals[name] == 1 else f"{name} ({seen[name]})")
    return titles


def render_pages_registry(plans: list[PagePlan]) -> str:
    """Return ``pages/__init__.py`` listing every page in frame order."""
    imports = sorted(f"from src.ui.pages.{p.slug}_page import {p.class_name}" for p in plans)
    registry = [
        f"    ({json.dumps(title)}, {p.class_name}),"
        for title, p in zip(nav_titles(plans), plans, strict=True)
    ]
    return "\n".join(
        [
            GENERATED_MARKER,
            "from __future__ import annotations",
            "",
            "from src.ui.pages.base_page import BasePage",
            *imports,
            "",
            "PAGES: list[tuple[str, type[BasePage]]] = [",
            *registry,
            "]",
            "",
        ]
    )


