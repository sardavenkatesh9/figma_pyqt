@dataclass(frozen=True, slots=True)
class PagePlan:
    """A frame together with the module and class names its page will use."""

    frame: FigmaFrame
    slug: str
    class_name: str

    @property
    def module_file(self) -> str:
        """File name of the page module."""
        return f"{self.slug}_page.py"


class SlugAllocator:
    """Hands out unique, importable module slugs for frame names.

    Remembering the next numeric suffix per base slug makes n identical names cost O(n)
    overall, where re-probing ``_2``, ``_3``, ... from scratch each time costs O(n^2).
    """

    def __init__(self) -> None:
        """Start with no slugs taken."""
        self._taken: set[str] = set()
        self._next_suffix: dict[str, int] = {}

    def allocate(self, name: str) -> str:
        """Return a slug for ``name`` that has not been returned before."""
        slug = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower() or "screen"
        if slug[0].isdigit() or keyword.iskeyword(slug):
            slug = f"screen_{slug}"
        candidate = slug
        while candidate in self._taken:
            suffix = self._next_suffix.get(slug, 2)
            self._next_suffix[slug] = suffix + 1
            candidate = f"{slug}_{suffix}"
        self._taken.add(candidate)
        return candidate


def class_name_for(slug: str) -> str:
    """Return the PascalCase page class name for a slug."""
    return "".join(part.capitalize() for part in slug.split("_") if part) + "Page"


def plan_pages(frames: list[FigmaFrame]) -> list[PagePlan]:
    """Assign a unique module and class name to every frame."""
    allocator = SlugAllocator()
    plans = []
    for frame in frames:
        slug = allocator.allocate(frame.name)
        plans.append(PagePlan(frame, slug, class_name_for(slug)))
    return plans


def _emit_node(
    node: FigmaNode, parent: FigmaNode, parent_var: str, lines: list[str], counter: list[int]
) -> None:
    counter[0] += 1
    var = f"node_{counter[0]}"
    label = json.dumps(node.characters or node.name)
    if node.type == "TEXT":
        lines.append(f"{_INDENT}{var} = QLabel({label}, {parent_var})")
    elif node.type in _BUTTON_TYPES and not node.children:
        lines.append(f"{_INDENT}{var} = QPushButton({label}, {parent_var})")
    else:
        lines.append(f"{_INDENT}{var} = QFrame({parent_var})")
        if node.children:
            lines.append(f'{_INDENT}{var}.setObjectName("card")')
    lines.append(f"{_INDENT}{var}.setToolTip({json.dumps(f'{node.name} ({node.type})')})")
    lines.append(
        f"{_INDENT}{var}.setGeometry("
        f"{node.x - parent.x}, {node.y - parent.y}, "
        f"{max(node.width, 1)}, {max(node.height, 1)})"
    )
    for child in node.children:
        _emit_node(child, node, var, lines, counter)


def render_page(plan: PagePlan) -> str:
    """Return the source of one page module."""
    frame = plan.frame
    body: list[str] = []
    counter = [0]
    for child in frame.children:
        _emit_node(child, frame, "canvas", body, counter)
    body_text = "\n".join(body)
    widgets = ["QWidget", *(n for n in _PAGE_WIDGETS if f"= {n}(" in body_text)]
    return "\n".join(
        [
            GENERATED_MARKER,
            "from __future__ import annotations",
            "",
            f"from PySide6.QtWidgets import {', '.join(sorted(widgets))}",
            "",
            "from src.ui.pages.base_page import BasePage",
            "",
            "",
            f"class {plan.class_name}(BasePage):",
            f"    TITLE = {json.dumps(frame.name)}",
            f"    FRAME_SIZE = ({max(frame.width, 1)}, {max(frame.height, 1)})",
            "",
            "    def build_canvas(self, canvas: QWidget) -> None:",
            f"        {json.dumps(f'Widgets for Figma frame {frame.name} ({frame.node_id}).')}",
            *body,
            "",
        ]
    )


def render_pages_registry(plans: list[PagePlan]) -> str:
    """Return ``pages/__init__.py`` listing every page in frame order."""
    imports = sorted(f"from src.ui.pages.{p.slug}_page import {p.class_name}" for p in plans)
    registry = [f"    ({json.dumps(p.frame.name)}, {p.class_name})," for p in plans]
    return "\n".join(
        [
            GENERATED_MARKER,
            "from __future__ import annotations",
            "",
            "from src.ui.pages.base_page import BasePage",
            *imports,
            "",
            "PAGES: list[tuple[str, type[BasePage]]] = [",
            *registry,
            "]",
            "",
        ]
    )


def render_main() -> str:
    """Return the generated ``main.py``."""
    return MAIN_SOURCE.format(marker=GENERATED_MARKER)


def render_main_window(project_name: str) -> str:
    """Return the generated ``main_window.py``."""
    return MAIN_WINDOW_SOURCE.format(marker=GENERATED_MARKER, title=json.dumps(project_name))


def render_readme(project_name: str, document_name: str) -> str:
    """Return the generated project's README."""
    return f"# {project_name}\n\nGenerated from {document_name}\n"


def render_pyproject() -> str:
    """Return the generated project's ``pyproject.toml``."""
    return '[project]\nname = "generated-app"\nversion = "0.1.0"\ndependencies = ["PySide6"]\n'
